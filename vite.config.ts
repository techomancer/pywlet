import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

function normalizeBasePath(raw?: string): string {
  if (!raw) return '/';
  let base = raw.trim();
  if (!base.startsWith('/')) base = `/${base}`;
  if (!base.endsWith('/')) base = `${base}/`;
  return base.replace(/\/+/g, '/');
}

function collectFiles(rootDir: string, currentDir = rootDir): string[] {
  const results: string[] = [];
  for (const entry of readdirSync(currentDir)) {
    const fullPath = join(currentDir, entry);
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      results.push(...collectFiles(rootDir, fullPath));
    } else if (stat.isFile()) {
      results.push(relative(rootDir, fullPath).replace(/\\/g, '/'));
    }
  }
  return results.sort();
}

/**
 * Generates `dist/sw.js` after the production build so Pywlet is:
 *  1. An installable offline-first PWA (app shell precached + runtime asset cache)
 *  2. Cross-Origin Isolated (COOP/COEP headers injected by the Service Worker),
 *     unlocking 4-thread SharedArrayBuffer WASM even on static hosts like GitHub Pages.
 */
function pywletPwaPlugin(): Plugin {
  let outDir = 'dist';

  return {
    name: 'pywlet-pwa-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir || 'dist';
    },
    closeBundle() {
      const distPath = join(process.cwd(), outDir);
      const files = collectFiles(distPath).filter((f) => f !== 'sw.js');

      const hash = createHash('sha256');
      for (const file of files) {
        hash.update(file);
        hash.update(':');
        hash.update(String(statSync(join(distPath, file)).size));
        hash.update('\n');
      }
      const cacheVersion = hash.digest('hex').slice(0, 10);
      const cacheName = `pywlet-pwa-${cacheVersion}`;

      // Fast, lightweight core app shell precached during `install`
      const corePrecache = ['./', './index.html'];
      // Large WASM binaries warmed in the background after activation so first-visit
      // Cross-Origin Isolation reload happens immediately without waiting for 21 MB.
      const backgroundPrecache: string[] = [];

      for (const file of files) {
        if (file === 'manifest.webmanifest' || file.startsWith('icons/')) {
          corePrecache.push(`./${file}`);
        } else if (
          /^assets\/(index|python|transformers\.worker|ort-wasm-.*)-[^/]+\.(js|css|mjs)$/.test(file)
        ) {
          corePrecache.push(`./${file}`);
        } else if (/^assets\/ort-wasm-.*\.wasm$/.test(file)) {
          backgroundPrecache.push(`./${file}`);
        }
      }

      // Also include any referenced entry assets in dist/index.html just in case
      const indexHtmlPath = join(distPath, 'index.html');
      try {
        const html = readFileSync(indexHtmlPath, 'utf8');
        for (const match of html.matchAll(/(?:src|href)="[^"]*?(assets\/[^"]+)"/g)) {
          const rel = `./${match[1]}`;
          if (!corePrecache.includes(rel)) corePrecache.push(rel);
        }
      } catch {
        // Ignore if index.html is missing
      }

      const swSource = `// Auto-generated by pywlet-pwa-service-worker Vite plugin
const CACHE_NAME = ${JSON.stringify(cacheName)};
const CORE_PRECACHE_URLS = ${JSON.stringify(corePrecache, null, 2)};
const BACKGROUND_PRECACHE_URLS = ${JSON.stringify(backgroundPrecache, null, 2)};

function withCrossOriginIsolationHeaders(response) {
  if (!response || response.status === 0) {
    return response;
  }
  if (
    response.headers.get('Cross-Origin-Opener-Policy') === 'same-origin' &&
    response.headers.get('Cross-Origin-Embedder-Policy') === 'require-corp' &&
    response.headers.get('Cross-Origin-Resource-Policy') === 'cross-origin'
  ) {
    return response;
  }
  const headers = new Headers(response.headers);
  headers.set('Cross-Origin-Opener-Policy', 'same-origin');
  headers.set('Cross-Origin-Embedder-Policy', 'require-corp');
  headers.set('Cross-Origin-Resource-Policy', 'cross-origin');
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

async function cacheUrls(cache, relUrls) {
  await Promise.all(
    relUrls.map(async (rel) => {
      try {
        const url = new URL(rel, self.registration.scope).href;
        const response = await fetch(url, { cache: 'reload' });
        if (response.status === 200) {
          const isolated = withCrossOriginIsolationHeaders(response);
          await cache.put(url, isolated);
        }
      } catch {
        // Ignore individual precache failures so install still succeeds
      }
    })
  );
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cacheUrls(cache, CORE_PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith('pywlet-pwa-') && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      );
      await self.clients.claim();

      // Warm large WASM runtime binaries in the background after activation
      // so the app is fully offline-ready without blocking initial COI reload.
      if (BACKGROUND_PRECACHE_URLS.length > 0) {
        const cache = await caches.open(CACHE_NAME);
        cacheUrls(cache, BACKGROUND_PRECACHE_URLS).catch(() => {});
      }
    })()
  );
});

async function handleNavigation(request) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const networkResponse = await fetch(request);
    const isolated = withCrossOriginIsolationHeaders(networkResponse);
    if (networkResponse.status === 200) {
      await cache.put(request, isolated.clone());
      const indexUrl = new URL('./index.html', self.registration.scope).href;
      await cache.put(indexUrl, isolated.clone());
    }
    return isolated;
  } catch {
    const cached =
      (await cache.match(request)) ||
      (await cache.match(new URL('./index.html', self.registration.scope).href)) ||
      (await cache.match(new URL('./', self.registration.scope).href));
    if (cached) {
      return withCrossOriginIsolationHeaders(cached);
    }
    return new Response('Pywlet is offline and no cached shell was found.', {
      status: 503,
      headers: { 'Content-Type': 'text/plain; charset=utf-8' },
    });
  }
}

async function handleAsset(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request);
  if (cached) {
    return withCrossOriginIsolationHeaders(cached);
  }
  const networkResponse = await fetch(request);
  const isolated = withCrossOriginIsolationHeaders(networkResponse);
  if (networkResponse.status === 200) {
    cache.put(request, isolated.clone()).catch(() => {});
  }
  return isolated;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (request.cache === 'only-if-cached' && request.mode !== 'same-origin') return;

  const url = new URL(request.url);
  // Leave cross-origin requests (HuggingFace model weights, local Ollama, etc.) untouched
  if (url.origin !== self.location.origin) return;
  if (!url.href.startsWith(self.registration.scope)) return;
  if (url.pathname.endsWith('/sw.js')) return;

  if (request.mode === 'navigate') {
    event.respondWith(handleNavigation(request));
    return;
  }

  event.respondWith(handleAsset(request));
});
`;

      writeFileSync(join(distPath, 'sw.js'), swSource, 'utf8');
    },
  };
}

export default defineConfig({
  base: normalizeBasePath(process.env.VITE_BASE_PATH),
  plugins: [pywletPwaPlugin()],
  server: {
    port: 5173,
    headers: {
      // Required for SharedArrayBuffer (Python step debugger & multi-threaded WASM)
      'Cross-Origin-Opener-Policy': 'same-origin',
      'Cross-Origin-Embedder-Policy': 'require-corp',
    },
  },
  preview: {
    port: 4173,
    headers: {
      'Cross-Origin-Opener-Policy': 'same-origin',
      'Cross-Origin-Embedder-Policy': 'require-corp',
    },
  },
  worker: {
    format: 'es',
  },
  optimizeDeps: {
    exclude: ['@huggingface/transformers'],
  },
});
